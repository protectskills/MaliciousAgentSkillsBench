def mask_value(value: str | None, visible: int = 4) -> str:
    if not value:
        return "missing"
    if len(value) <= visible:
        return "*" * len(value)
    return value[:visible] + "*" * 8


def mask_path(value: str | None) -> str:
    if not value:
        return "not configured"
    path = Path(value).expanduser()
    parent = path.parent.name or str(path.parent)
    return f".../{parent}/{path.name}"


def expand_path(value: str | None) -> Path | None:
    if not value:
        return None
    return Path(value).expanduser()


def resolve_input_path(value: str, base: Path = ROOT) -> Path:
    path = Path(value).expanduser()
    if path.is_absolute() or path.exists():
        return path
    candidates = [base / path, base.parent / path]
    for candidate in candidates:
        if candidate.exists():
            return candidate
    return path


def ask_secret_value(label: str, current: str = "", required: bool = False) -> str:
    state = f"configured ({mask_value(current)})" if current else "not configured"
    click.echo(f"{label}: {state}")
    value = click.prompt(
        f"New {label} (leave blank to keep)",
        default="",
        hide_input=sys.stdin.isatty(),
        show_default=False,
    )
    if value:
        return value
    if required and not current:
        click.echo(click.style(f"{label} remains missing.", fg="yellow"))
    return current


