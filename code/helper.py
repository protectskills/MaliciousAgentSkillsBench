@cli.command()
@click.pass_context
def clean(ctx: click.Context) -> None:
    """Remove local runtime outputs, keeping code and env files."""
    groups = [
        ("crawl data", [ROOT / "data"]),
        ("downloaded repo archives", [ROOT / "workspace" / "zip"]),
        ("extracted repositories", [ROOT / "workspace" / "repo"]),
        ("repo-level static scan reports", [ROOT / "workspace" / "static"]),
        ("optional Claude Code analysis results", [ROOT / "scan_results"]),
        ("dynamic execution logs", [ROOT / "workspace" / "dynamic"]),
        ("legacy dynamic execution logs", [ROOT / "execution_logs"]),
        ("task queues", [ROOT / "tasks"]),
        ("helper/build logs", [ROOT / "logs"]),
    ]

    selected: List[Path] = []
    click.echo("Select runtime outputs to remove:")
    for label, paths in groups:
        existing = [path for path in paths if path.exists()]
        if not existing:
            click.echo(f"  - {label}: not present")
            continue
        count = sum(1 for path in existing for _ in path.rglob("*"))
        if click.confirm(f"Delete {label} ({count} entries)?", default=False):
            selected.extend(existing)

    if not selected:
        click.echo("Nothing selected.")
        return

    click.echo("Selected paths:")
    for target in selected:
        click.echo(f"  {target}")
    if not click.confirm("Confirm deletion?", default=False):
        click.echo("Clean cancelled.")
        return

    for target in selected:
        if target.exists():
            shutil.rmtree(target)
    click.echo(click.style("Cleaned selected runtime outputs", fg="green"))


