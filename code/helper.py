def load_env(path: Path) -> Dict[str, str]:
    values: Dict[str, str] = {}
    if not path.exists():
        return values
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        value = value.strip()
        try:
            parsed = shlex.split(value, comments=False, posix=True)
            values[key.strip()] = " ".join(parsed) if parsed else ""
        except ValueError:
            values[key.strip()] = value.strip('"').strip("'")
    return values


def write_env(path: Path, values: Dict[str, str]) -> None:
    ordered = list(DEFAULTS)
    extra = sorted(k for k in values if k not in DEFAULTS)
    lines = [
        "# Local reproduction environment.",
        "# Generated by helper.py. Do not commit this file.",
        "",
    ]
    for key in ordered + extra:
        if key in values and values[key] != "":
            lines.append(f"{key}={shlex.quote(values[key])}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    path.chmod(0o600)


