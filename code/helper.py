@cli.command()
@click.option(
    "--mode",
    type=click.Choice(["lite", "load-tar", "none", "full-cpu", "full-custom"]),
    default=None,
)
@click.option("--verbose", is_flag=True, help="Stream full Docker build output instead of concise progress.")
@click.pass_context
def build(ctx: click.Context, mode: str | None, verbose: bool) -> None:
    """Pull or build the Docker sandbox image."""
    env = merged_env(ctx.obj["env_file"])
    docker = docker_cmd(env)
    if not command_exists(docker[0]):
        raise click.ClickException(f"{docker[0]} is not installed or not on PATH.")
    if not docker_access_ok(docker):
        raise click.ClickException(
            "Docker is installed but this Docker command cannot access the daemon. "
            "Add the user to the docker group and start a new login shell, run helper with sudo, or set DOCKER_CMD='sudo docker'."
        )
    mode = mode or click.prompt(
        "Image mode",
        type=click.Choice(["lite", "load-tar", "none", "full-cpu", "full-custom"]),
        default="lite",
    )
    image = env.get("DOCKER_IMAGE", DEFAULTS["DOCKER_IMAGE"])
    if mode == "load-tar":
        default_tar = ROOT / "docker-images" / "claude-skill-sandbox-lite.tar.gz"
        tar_path = resolve_input_path(ask_value("Image tar or tar.gz file", str(default_tar)))
        if not tar_path.exists():
            raise click.ClickException(f"Image archive not found: {tar_path}")
        load_cmd = docker + ["load", "-i", str(tar_path)]
        click.echo(click.style("$ " + " ".join(load_cmd), fg="cyan"))
        result = subprocess.run(load_cmd, cwd=ROOT, env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
        if result.stdout:
            click.echo(result.stdout.rstrip())
        if result.returncode != 0:
            raise click.ClickException(f"Docker load failed with exit code {result.returncode}")
        loaded = re.findall(r"Loaded image:\s*(\S+)", result.stdout or "")
        if loaded:
            env_file: Path = ctx.obj["env_file"]
            values = env_file_values_for_update(env_file, env)
            values["DOCKER_IMAGE"] = loaded[-1]
            write_env(env_file, values)
            click.echo(click.style(f"Updated DOCKER_IMAGE={loaded[-1]} in {env_file}", fg="green"))
        else:
            click.echo(click.style("Docker load completed, but no image tag was reported; DOCKER_IMAGE was not changed.", fg="yellow"))
        return

    if mode == "lite" and image == DEFAULTS["DOCKER_IMAGE"]:
        if click.confirm(f"Pull prebuilt image {image}?", default=True):
            code = run(docker + ["pull", image], env=env)
            if code != 0:
                raise click.ClickException(f"Docker pull failed with exit code {code}")
        return

    args = docker + ["build", "-t", image, "-f", "Dockerfile", "--build-arg", f"NODE_MAJOR={env.get('NODE_MAJOR', '22')}"]
    if mode == "none":
        args += ["--build-arg", "NOVA_MODE=none"]
    elif mode == "lite":
        args += ["--build-arg", "NOVA_MODE=lite"]
    elif mode == "full-cpu":
        args += ["--build-arg", "NOVA_MODE=full"]
    else:
        torch_spec = ask_value("NOVA_TORCH_SPEC", env.get("NOVA_TORCH_SPEC", "torch>=2.5,<3"))
        torch_index = ask_value("NOVA_TORCH_INDEX_URL", env.get("NOVA_TORCH_INDEX_URL", ""))
        args += ["--build-arg", "NOVA_MODE=full", "--build-arg", f"NOVA_TORCH_SPEC={torch_spec}"]
        args += ["--build-arg", f"NOVA_TORCH_INDEX_URL={torch_index}"]
    args.append(".")
    if click.confirm("Run Docker build?", default=True):
        code = run_docker_build(args, env=env, verbose=verbose)
        if code != 0:
            raise click.ClickException(f"Docker build failed with exit code {code}")


@cli.command(name="run")
@click.option("--analyze/--no-analyze", default=None, help="Run optional Claude Code analysis after dynamic execution.")
@click.option("--quiet/--verbose", "quiet", default=None, help="Override EXEC_QUIET: --quiet prints one status line per skill, --verbose streams full output. Default (auto) goes quiet for batches larger than EXEC_QUIET_THRESHOLD.")
@click.pass_context
def run_experiment(ctx: click.Context, analyze: bool | None, quiet: bool | None) -> None:
    """Run the default small-batch experiment."""
    env_file: Path = ctx.obj["env_file"]
    env = merged_env(env_file)
    if analyze is not None:
        env["ENABLE_CC_ANALYSIS"] = "true" if analyze else "false"
    if quiet is not None:
        env["EXEC_QUIET"] = "true" if quiet else "false"
    if not env.get("SKILLSMP_API_KEY"):
        raise click.ClickException("SKILLSMP_API_KEY is required (generate one at https://skillsmp.com, account settings). Run: python3 helper.py init")
    if not claude_auth_available(env):
        raise click.ClickException("Claude login was not found. Run Claude Code locally, set CLAUDE_CREDENTIALS_FILE, or set CLAUDE_SETTINGS_FILE.")
    if is_enabled(env.get("EXEC_REPORT_MODE", "false")):
        env["EXEC_TIMEOUT"] = env.get("EXEC_REPORT_TIMEOUT", DEFAULTS["EXEC_REPORT_TIMEOUT"])

    print_banner()
    analysis_enabled = env.get("ENABLE_CC_ANALYSIS", "false").lower() == "true"
    click.echo(f"Default small-batch experiment (CC analysis: {'enabled' if analysis_enabled else 'disabled'})")
    click.echo("Default small-batch experiment commands:")
    steps = commands_for_run(env)
    for index, (overrides, cmd) in enumerate(steps, 1):
        merged = {k: overrides[k] for k in sorted(overrides)}
        prefix = " ".join(f"{k}={v!r}" for k, v in merged.items())
        click.echo(f"  [{index}/{len(steps)}] {prefix + ' ' if prefix else ''}{' '.join(cmd)}")
    if not click.confirm("Run these commands?", default=True):
        return

    for index, (overrides, cmd) in enumerate(steps, 1):
        click.echo(click.style(f"Step {index}/{len(steps)}: {' '.join(cmd)}", fg="cyan"))
        step_env = dict(env)
        step_env.update(overrides)
        code = run(cmd, env=step_env)
        if code != 0:
            raise click.ClickException(f"Step {index}/{len(steps)} failed with exit code {code}: {' '.join(cmd)}")

    continue_execution(env)


