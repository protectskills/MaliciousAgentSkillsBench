def prompt_for_skill(skill_name: str, template: str) -> str:
    prompt = template.replace("{skill_name}", skill_name)
    return prompt.replace("|", "/")


def skill_md_path(path: Path) -> Path | None:
    for name in ("SKILL.md", "skill.md"):
        candidate = path / name
        if candidate.is_file():
            return candidate
    return None


def discover_skill_dirs(root: Path, recursive: bool = False) -> List[Path]:
    root = root.expanduser().resolve()
    if not root.exists():
        raise click.ClickException(f"Skill directory not found: {root}")
    if not root.is_dir():
        raise click.ClickException(f"Skill path is not a directory: {root}")

    found: List[Path] = []
    if skill_md_path(root):
        found.append(root)

    candidates = root.rglob("*") if recursive else root.iterdir()
    for path in candidates:
        if path.is_dir() and skill_md_path(path):
            found.append(path.resolve())

    skills = sorted(set(found), key=lambda p: str(p))
    if not skills:
        scope = "recursively" if recursive else "in direct child directories"
        raise click.ClickException(f"No skills found {scope}: {root}. Expected directories containing SKILL.md.")
    return skills


def write_skill_queue(
    skill_dirs: List[Path],
    queue_file: Path,
    prompt_template: str,
    limit: int = 0,
    repo_id: str = "local_skills",
    risk_level: str = "LOCAL",
) -> int:
    queue_file = queue_file.expanduser()
    if not queue_file.is_absolute():
        queue_file = ROOT / queue_file
    queue_file.parent.mkdir(parents=True, exist_ok=True)

    selected = skill_dirs[:limit] if limit > 0 else skill_dirs
    lines = []
    for skill_dir in selected:
        skill_name = skill_dir.name.replace("|", "/")
        prompt = prompt_for_skill(skill_name, prompt_template)
        lines.append("|".join([skill_name, str(skill_dir), prompt, repo_id, risk_level, "local"]))

    queue_file.write_text("\n".join(lines) + ("\n" if lines else ""), encoding="utf-8")
    return len(lines)


def preview_queue(queue_file: Path, limit: int = 5) -> None:
    if not queue_file.exists():
        click.echo("Queue file does not exist yet.")
        return
    lines = [line.strip() for line in queue_file.read_text(encoding="utf-8").splitlines() if line.strip()]
    click.echo(f"Queue: {queue_file}")
    click.echo(f"Tasks: {len(lines)}")
    for line in lines[:limit]:
        parts = line.split("|")
        if len(parts) >= 2:
            click.echo(f"  {parts[0]} -> {parts[1]}")
    if len(lines) > limit:
        click.echo(f"  ... {len(lines) - limit} more")


def queue_progress(queue_file: Path, state_file: Path, retry_timeout_artifacts: bool = False) -> Tuple[int, int, int]:
    if not queue_file.exists():
        return 0, 0, 0
    lines = [line.strip() for line in queue_file.read_text(encoding="utf-8").splitlines() if line.strip()]
    tasks = [parse_task(line) for line in lines]
    valid = [task for task in tasks if task["valid"]]
    completed = load_completed_tasks(
        state_file,
        Config(str(ROOT / "config.yaml")),
        retry_timeout_artifacts=retry_timeout_artifacts,
    )
    completed_count = sum(1 for task in valid if task["task_id"] in completed)
    pending_count = len(valid) - completed_count
    return len(valid), completed_count, pending_count


def continue_execution(env: Dict[str, str]) -> None:
    queue_file = ROOT / "tasks" / "run_queue.txt"
    state_file = Path(env.get("RUN_QUEUE_STATE_FILE", str(ROOT / "tasks" / "run_queue_state.jsonl")))
    if not state_file.is_absolute():
        state_file = ROOT / state_file

    if not sys.stdin.isatty():
        return

    while True:
        retry_artifacts = env.get("RETRY_TIMEOUT_ARTIFACTS", "false").lower() == "true"
        total, completed, pending = queue_progress(queue_file, state_file, retry_artifacts)
        click.echo("")
        click.echo(f"Execution queue: total={total}, completed={completed}, pending={pending}")
        if pending <= 0:
            click.echo(click.style("No pending queue entries remain.", fg="green"))
            return
        try:
            if not click.confirm("Continue executing pending skills?", default=False):
                return

            default_limit = int(env.get("RUN_QUEUE_LIMIT", "1") or "1")
            limit = click.prompt("Skills to execute this round (0 means all pending)", type=int, default=default_limit)
            default_workers = int(env.get("EXEC_WORKERS", "1") or "1")
            workers = click.prompt("Workers", type=int, default=default_workers)
            timeout_key = "EXEC_REPORT_TIMEOUT" if is_enabled(env.get("EXEC_REPORT_MODE")) else "EXEC_TIMEOUT"
            default_timeout = int(env.get(timeout_key, DEFAULTS[timeout_key]) or DEFAULTS[timeout_key])
            timeout = click.prompt("Timeout seconds", type=int, default=default_timeout)
        except (click.Abort, EOFError):
            return

        step_env = dict(env)
        step_env.update(
            {
                "RUN_QUEUE_LIMIT": str(limit),
                "RUN_QUEUE_STATE_FILE": str(state_file),
                "EXEC_WORKERS": str(workers),
                "EXEC_TIMEOUT": str(timeout),
                "EXEC_REPORT_MODE": "true" if is_enabled(env.get("EXEC_REPORT_MODE")) else "false",
            }
        )
        code = run(["bash", "scripts/06_execute.sh"], env=step_env)
        if code != 0:
            raise click.ClickException(f"Continue execution failed with exit code {code}: bash scripts/06_execute.sh")


def main_menu(ctx: click.Context, env_file: Path) -> None:
    """Small interactive menu for the common reproduction path."""
    actions = {
        "1": ("init", init, "create or update .env"),
        "2": ("doctor", doctor, "check Python, Docker, credentials, and image"),
        "3": ("image", build, "pull or build the Docker sandbox image"),
        "4": ("run", run_experiment, "run the default small-batch experiment"),
        "5": ("status", status, "show or edit configuration and runtime outputs"),
        "6": ("clean", clean, "remove selected runtime outputs"),
        "7": ("exit", None, "leave helper"),
    }

    while True:
        print_banner()
        click.echo("Choose an action:")
        for key, (name, _callback, desc) in actions.items():
            click.echo(f"  {key}. {name:<6} {desc}")
        choice = click.prompt("Select", type=click.Choice(list(actions)), default="4", show_default=True)
        action, callback, _desc = actions[choice]
        if action == "exit":
            return

        click.echo("")
        try:
            ctx.invoke(callback)
        except click.ClickException as exc:
            click.echo(click.style(f"Error: {exc.message}", fg="red"))
        click.echo("")
        if not click.confirm("Back to menu?", default=True):
            return


